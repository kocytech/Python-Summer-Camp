# liste öğeleri indexleme ile ulaşılabilir.

meyve = ["elma", "armut", "muz", "çilek", "karpuz", "kavun", "portakal", "mandalina"]
print(meyve[0]) # elma
# negatif indexleme ile sondan başa doğru sayabiliriz.
print(meyve[-1]) # mandalina

# aralık indexleme ile birden fazla öğeye ulaşabiliriz.
print(meyve[2:6]) # ['muz', 'çilek', 'karpuz']